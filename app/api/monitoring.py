"""Delivery Monitor and Escalation Engine — Phase 5's HTTP surface (CLAUDE.md §8).

    GET /monitoring/alerts   the internal alert feed, with SLA escalations
    GET /monitoring/rules    the shipped SLA rule table, as policy

`app/services/monitoring/` and `app/services/escalation/` were fully built and
tested with nothing able to call them. This module is the call: it reads the
systems of record, shapes them into a `MonitorContext` / `SlaFacts`, and
serialises what the two pure services hand back. No detector, no threshold, no
weight and no comparison is reimplemented here — grep this file for a number and
the only ones you will find are a period-length guard and an hours-per-hour
divisor.

CEILING: ALERT, INTERNAL ONLY (§8)
==================================
"Delivery Monitor — attendance, usage, syllabus anomalies, risk scoring.
Ceiling: **Alert (internal only)**." That is autonomy level 1, Observe: read,
report, alert internally.

Both endpoints are `GET`. Nothing here sends, notifies, queues an outbound comm,
marks, acknowledges, resolves, approves or releases anything (R3, R4), and
nothing here writes a row of any kind — not even an audit row, because §11 wants
audit rows for state *transitions* and a read is not one. `escalation.raised` /
`escalation.routed` (`app/services/escalation/audit.py`) belong to the scheduled
evaluation that persists escalations; that path does not exist yet and this
module deliberately does not become it by writing from a GET handler.

`build_alert()` refuses an external audience, and the audience passed below is
always `(principal.persona,)` behind `require_internal()`. A trainer or a College
login is refused before a single row is read.

NO LLM (§8)
===========
"Escalation Engine — deterministic SLA rules. **Not LLM judgement.**" This module
imports nothing from `app.core.llm` or `app.agents`, and neither endpoint takes
an `include_narrative`-style flag. Every escalation below is a `Decimal` compared
to a `Decimal` threshold from `DEFAULT_RULES`, and its `reason` is generated by
`SlaRule.explain()` from the rule row itself.

R5 / §4 — WHERE THE WALL IS
===========================
We are on a `BYPASSRLS` service-role connection (`app/db/session.py`), so the
policies never run for us and reach is enforced in code, exactly as `reports.py`
and `programs.py` do it. `_reachable_programs()` is the wall: the SQL predicate
narrows the read, and the Python filter after it is what actually guarantees the
result, because on this connection the database will happily hand back every
college in the country. An LDE Executive therefore sees their own campus and
zero rows for anything else — `tests/unit/test_api_monitoring.py` asserts the
zero, not the 403.

COMMERCIALS: NOTHING HERE IS BEHIND THAT WALL, AND THAT IS CHECKED, NOT ASSUMED
==============================================================================
§4 gives an LDE Executive "attendance, batches, daily tasks. **No commercials**",
and this feed is squarely their daily work — so the question is whether any
figure that leaves this module is commercial. Audited field by field:

* Anomaly `detail` (`app/services/monitoring/detectors.py`) carries day counts,
  dates, hour counts, absence rates, active-learner counts and syllabus
  percentages. No amount, no rate, no invoice.
* Escalation `measured` / `threshold` are hours, unmarked-day counts and the
  monitor's own risk score. `SlaMetric` has no monetary member.
* Trainer identity is surfaced as `full_name` only. PAN seeds the invoice number
  (§6) and is deliberately not exported here.

So `require_commercials()` is **not** called, and the omission is the finding
rather than an oversight. Two consequences follow and are honoured below:

* `SlaMetric.PAYOUT_HOURS_BLOCKED` is left UNMEASURED. Measuring it means reading
  `remuneration_sheets`, which is behind the wall, and half-populating this feed
  for a Manager and not an LDE Executive would put a commercial-visibility branch
  inside a non-commercial screen. When a payout-blocked escalation is wanted it
  belongs in `payouts.py`, behind `require_commercials()`.
* If a monetary field is ever added to an anomaly, an SLA metric or this
  response, this endpoint must gain `require_commercials()` in the same diff.

WHAT IS DELIBERATELY DARK
=========================
Five of the nine detectors cannot fire from this endpoint today, and none of them
is faked. `DETECTORS` is 4 attendance + 2 usage + 3 syllabus; attendance is the
only family with a table behind it, so the two usage and three syllabus detectors
are dark. (This paragraph read "four" while already listing five function names
below — the prose was wrong, not the list.)

* usage (`detect_no_activity`, `detect_low_active_share`) — §14 Q6 is open
  ("EdTech platform access: direct DB, API, or neither?"), so there is no
  platform-engagement row anywhere in `app/db/models.py`. `attendance_records` is
  STUDENT class attendance and mapping it onto `UsageSignal` would report a
  delivery fact the platform never said (R1).
* syllabus (`detect_syllabus_*`) — no column stores a completion reading.

`MonitorContext.usage` and `.syllabus` are therefore `None`, which the detectors
already treat as "silent", and `SlaMetric.ESCALATION_HOURS_UNACKNOWLEDGED` is
unmeasured because no `escalations` table exists to have gone unacknowledged.
"Not measured is not zero" is the engine's own rule; this module obeys it by
omitting the key rather than passing a placeholder.
"""

