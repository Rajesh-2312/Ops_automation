    score: DecimalOut
    band: RiskBand
    deployments: tuple[DeploymentRiskOut, ...]
    escalations: tuple[EscalationOut, ...]
    #: Metrics the rule table can refer to but which nothing measured for this
    #: program. Listed because "not measured is not zero" (`engine.py`) is
    #: invisible otherwise — a silent rule and a passing rule look identical.
    unmeasured_metrics: tuple[str, ...]


