async def sla_rules(principal: CurrentPrincipal) -> SlaRulesOut:
    """`DEFAULT_RULES` verbatim, in table order.

    §8's promise is that "a reviewer can read why something escalated without
    running anything", and that only holds if the rule table is readable by the
    people the escalations land on. Internal only for the same reason the feed is:
    the rungs it names are the §4 chain, which is byteXL's org chart.

    Nothing here is configurable through this endpoint, and there is no PUT. A
    rule change is an edit to `rules.py` in a diff someone reviews — a threshold
    editable at runtime is a threshold nobody can reconstruct after the fact.
    """
    require_internal(principal)
    return SlaRulesOut(
        rules=tuple(
            SlaRuleOut.of(rule, measured=rule.metric in MEASURED_METRICS) for rule in DEFAULT_RULES
        ),
        measured_metrics=tuple(sorted(m.value for m in MEASURED_METRICS)),
        unmeasured_metrics=tuple(sorted(m.value for m in SlaMetric if m not in MEASURED_METRICS)),
    )


