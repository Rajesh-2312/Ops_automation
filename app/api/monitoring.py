class AnomalyOut(BaseModel):
    """One thing the Delivery Monitor observed. Never a conclusion (§8)."""

    model_config = ConfigDict(frozen=True)

    code: str
    severity: str
    message: str
    detail: dict[str, str]

    @classmethod
    def of(cls, anomaly: Anomaly) -> AnomalyOut:
        return cls(
            code=anomaly.code.value,
            severity=anomaly.severity.value,
            message=anomaly.message,
            # Already `str`-valued at construction (`detectors._anomaly`), so this
            # copies the operative figures out without reformatting one of them.
            detail=dict(anomaly.detail),
        )


class DeploymentRiskOut(BaseModel):
    """One trainer-on-a-batch, assessed. The grain `trainer_attendance` is kept at.

    The monitor is not run per program: a program with three deployments has three
    tracksheets, and `expand_period()` requires each calendar day exactly once, so
    merging them would duplicate days and make "unmarked" incalculable. The
    program-level score above is the worst of these, never their sum.
    """

    model_config = ConfigDict(frozen=True)

    deployment_id: UUID
    trainer_name: str
    batch_name: str
    period_start: dt.date
    period_end: dt.date
    elapsed_through: dt.date
    score: DecimalOut
    band: RiskBand
    #: `InternalAlert.headline` and `.lines`, exactly as `alerts.build_alert()`
    #: rendered them for this caller's persona. Rendered text, never a fact — the
    #: structured `anomalies` below are what a client should compute from (R1).
    headline: str
    lines: tuple[str, ...]
    anomalies: tuple[AnomalyOut, ...]


class EscalationOut(BaseModel):
    """One SLA rule that fired, with the numbers that made it fire, and where it landed.

    `reason` is `SlaRule.explain()` plus the measured value — generated from the
    rule row, not written about it, so an escalation whose explanation disagrees
    with its threshold is not expressible.
    """

    model_config = ConfigDict(frozen=True)

    code: str
    metric: str
    comparison: str
    measured: DecimalOut
    threshold: DecimalOut
    severity: str
    reason: str
    requested_tier: EscalationTier
    resolved_tier: EscalationTier
    recipient_persona: Persona
    #: How many internal users at `resolved_tier` reach this college. Ids are not
    #: exported: the count and the tier are what `escalation.routed` records, and
    #: a feed that names individuals invites being read as an assignment.
    recipient_count: int
    #: True when an unstaffed rung was climbed (§4). A Senior Manager asking "why
    #: is this on my desk" reads it here.
    climbed: bool
    #: True when no internal user could be found on any rung. An ops gap in the
    #: assignment tables, surfaced rather than raised.
    unrouted: bool

    @classmethod
    def of(cls, routed: EscalationRecipients) -> EscalationOut:
        e = routed.escalation
        return cls(
            code=e.code.value,
            metric=e.metric.value,
            comparison=e.comparison.value,
            measured=e.measured,
            threshold=e.threshold,
            severity=e.severity.value,
            reason=e.reason,
            requested_tier=routed.requested_tier,
            resolved_tier=routed.resolved_tier,
            recipient_persona=routed.persona,
            recipient_count=len(routed.user_ids),
            climbed=routed.requested_tier is not routed.resolved_tier,
            unrouted=routed.is_unrouted,
        )


class ProgramRiskOut(BaseModel):
    """One program's delivery risk, its deployments and its SLA escalations."""

    model_config = ConfigDict(frozen=True)

    program_id: UUID
    program_name: str
    program_type: ProgramType
    college_id: UUID
    college_name: str
    stage: str
    #: The worst deployment's score, not the sum. Summing would make a program
