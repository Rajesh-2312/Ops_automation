async def _reachable_programs(
    session: AsyncSession,
    principal: Principal,
    program_id: UUID | None,
    college_id: UUID | None,
) -> list[Program]:
    """Every program the caller reaches, optionally narrowed to one.

    THE WALL (R5). On a `BYPASSRLS` connection the SQL predicate is an
    optimisation and the Python filter is the guarantee — the database will
    return every program in the estate if asked, so the last line here is what
    makes an LDE Executive's feed contain their campus and nothing else.

    A named `program_id` or `college_id` outside reach is a 403 rather than an
    empty list: the caller asserted something specific and is entitled to be told
    it was refused. An unnamed sweep is silently narrowed, because "everything you
    reach" cannot be refused.
    """
    if program_id is not None:
        program = await session.get(Program, program_id)
        if program is None:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Program not found")
        require_college_reach(principal, program.college_id)
        if college_id is not None and program.college_id != college_id:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="That program does not belong to that college",
            )
        return [program]

    if college_id is not None:
        require_college_reach(principal, college_id)
        scope = frozenset({college_id})
    else:
        scope = principal.college_ids

    if not scope:
        return []
    rows = await _all(session, Program, Program.college_id.in_(scope))
    return [p for p in rows if p.college_id in scope]


