@router.get(
    "/alerts",
    response_model=AlertFeedOut,
    status_code=status.HTTP_200_OK,
    summary="Internal delivery-risk alerts and SLA escalations across the caller's reach",
)
async def alert_feed(
    principal: CurrentPrincipal,
    session: Session,
    program_id: Annotated[UUID | None, Query()] = None,
    college_id: Annotated[UUID | None, Query()] = None,
    period_start: Annotated[dt.date | None, Query()] = None,
    period_end: Annotated[dt.date | None, Query()] = None,
    as_of: Annotated[dt.datetime | None, Query()] = None,
) -> AlertFeedOut:
    """Run the Delivery Monitor and the Escalation Engine over everything in reach.

    Internal only, and available to an LDE Executive: attendance and batches are
    §4's description of their day, and nothing in this response is commercial —
    see the module docstring, which audits that field by field.

    Computed on request rather than read from a table. There is no `alerts` or
    `escalations` table in `supabase/migrations/`, and inventing one from a read
    endpoint is not this workstream's to do; both services are pure functions of
    signals that are already stored, so the feed is reproducible from its inputs.
    Pass `as_of` to reproduce a past run exactly — nothing below reads a clock
    once that argument is bound.

    `period_start` / `period_end` default to the calendar month containing
    `as_of`, which is the period a payout cycle is cut on (§6).
    """
    require_internal(principal)
    observed_at = _as_of(as_of)
    start, end = _period(period_start, period_end, observed_at)

    programs = await _reachable_programs(session, principal, program_id, college_id)
    colleges = {
        c.id: c
        for c in await _all(
            session, College, College.id.in_([p.college_id for p in programs]) if programs else None
        )
    }

    batches = await _in(session, Batch, Batch.program_id, [p.id for p in programs])
    batches_by_program: dict[UUID, list[Batch]] = defaultdict(list)
    for batch in batches:
        batches_by_program[batch.program_id].append(batch)

    deployments = await _in(session, Deployment, Deployment.batch_id, [b.id for b in batches])
    trainers = {
        t.id: t
        for t in await _in(session, Trainer, Trainer.id, [d.trainer_id for d in deployments])
    }
    batch_names = {b.id: b.name for b in batches}

    marks = await _marks(session, [d.id for d in deployments], start, end)
    tasks = await _in(session, Task, Task.program_id, [p.id for p in programs])
    documents = await _in(
        session, ProgramDocument, ProgramDocument.program_id, [p.id for p in programs]
    )
    directory = await _staff_directory(session, [p.college_id for p in programs])

    deployments_by_batch: dict[UUID, list[Deployment]] = defaultdict(list)
    for deployment in deployments:
        deployments_by_batch[deployment.batch_id].append(deployment)

    out: list[ProgramRiskOut] = []
    for program in programs:
        program_deployments = [
            d for b in batches_by_program[program.id] for d in deployments_by_batch[b.id]
        ]
        assessed = _assess_deployments(program, program_deployments, marks, start, end, observed_at)
        rendered = tuple(
            _deployment_out(
                deployment,
                assessment,
                signal,
                principal.persona,
                trainer_name=(
                    trainers[deployment.trainer_id].full_name or "unnamed"
                    if deployment.trainer_id in trainers
                    else "unknown"
                ),
                batch_name=batch_names.get(deployment.batch_id, "unknown"),
            )
            for deployment, assessment, signal in assessed
        )

        metrics = _sla_metrics(
            assessed,
            [t for t in tasks if t.program_id == program.id],
            [d for d in documents if d.program_id == program.id],
            observed_at,
        )
        decision = evaluate_sla(
            SlaFacts(
                subject_table="programs",
                subject_id=program.id,
                program_id=program.id,
                college_id=program.college_id,
                program_type=program.type,
                as_of=observed_at,
                metrics=metrics,
            )
        )
        escalations: list[EscalationOut] = []
        for fired in decision.escalations:
            # Routing climbs unstaffed rungs (§4), so it is resolved per firing
            # rather than once per program: two rules on one program can start at
            # different tiers and land in different places.
            escalations.append(EscalationOut.of(await resolve_recipients(fired, directory)))

        score = max((a.score for _, a, _ in assessed), default=Decimal(0))
        college = colleges.get(program.college_id)
        out.append(
            ProgramRiskOut(
                program_id=program.id,
                program_name=program.name,
                program_type=program.type,
                college_id=program.college_id,
                college_name=college.name if college else "unknown",
                stage=program.stage.value,
                score=score,
                band=band_for_score(score),
                deployments=rendered,
                escalations=tuple(escalations),
                unmeasured_metrics=_unmeasured(metrics),
            )
        )

    out.sort(key=lambda p: (-p.score, p.college_name, p.program_name))
    band_counts = {band.value: sum(1 for p in out if p.band is band) for band in RiskBand}
    return AlertFeedOut(
        as_of=observed_at,
        period_start=start,
        period_end=end,
        audience=principal.persona,
        programs=tuple(out),
        program_count=len(out),
        deployment_count=sum(len(p.deployments) for p in out),
        escalation_count=sum(len(p.escalations) for p in out),
        band_counts=band_counts,
    )


