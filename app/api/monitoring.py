async def _all(
    session: AsyncSession, model: type[Any], *criteria: ColumnExpressionArgument[bool] | None
) -> Sequence[Any]:
    """`SELECT * FROM model WHERE ...`, as a list. The only query shape here."""
    where = [c for c in criteria if c is not None]
    return (await session.execute(select(model).where(*where))).scalars().all()


async def _in(
    session: AsyncSession,
    model: type[Any],
    column: InstrumentedAttribute[Any],
    values: Iterable[UUID],
) -> list[Any]:
    """`WHERE column IN (...)`, short-circuiting on an empty list.

    An empty `IN ()` is legal SQL that matches nothing, but building the statement
    at all costs a round trip per empty level, and the levels nest four deep here.
    """
    unique = sorted(set(values))
    if not unique:
        return []
    return list(await _all(session, model, column.in_(unique)))


async def _marks(
    session: AsyncSession, deployment_ids: Sequence[UUID], start: dt.date, end: dt.date
) -> dict[UUID, list[TrainerAttendance]]:
    """Every trainer-day mark in the window, grouped by deployment."""
    rows = (
        await _all(
            session,
            TrainerAttendance,
            TrainerAttendance.deployment_id.in_(sorted(set(deployment_ids))),
            TrainerAttendance.mark_date >= start,
            TrainerAttendance.mark_date <= end,
        )
        if deployment_ids
        else []
    )
    grouped: dict[UUID, list[TrainerAttendance]] = defaultdict(list)
    for row in rows:
        grouped[row.deployment_id].append(row)
    return grouped


class _StaffDirectory:
    """`ReachDirectory` (`app/services/escalation/targets.py`) bound to the database.

    Pre-resolved into a mapping rather than querying per escalation: a feed over
    thirty programs raises the same tiers against the same colleges over and over,
    and the Protocol requires a stable order across calls, which one sorted build
    gives for free.

    Reach is read from `user_college_assignments` and `user_cluster_assignments`
    with `colleges.cluster_id` expanding a cluster (§4) — never inferred from
    `profiles.college_id`, which serves the College persona alone.
    """

    __slots__ = ("_by_tier_college",)

    def __init__(self, by_tier_college: _TierMap) -> None:
        self._by_tier_college = by_tier_college

    async def users_at_tier(self, tier: EscalationTier, college_id: UUID) -> tuple[UUID, ...]:
        return self._by_tier_college.get((tier, college_id), ())


async def _staff_directory(session: AsyncSession, college_ids: Sequence[UUID]) -> _StaffDirectory:
    """Who, on each rung, reaches each college in scope."""
    scope = sorted(set(college_ids))
    if not scope:
        return _StaffDirectory({})

    profiles = await _all(session, Profile, Profile.role.in_(sorted(_TIER_BY_PERSONA)))
    tier_of = {p.id: _TIER_BY_PERSONA[p.role] for p in profiles if p.role in _TIER_BY_PERSONA}

    reach: dict[UUID, set[UUID]] = defaultdict(set)
    for row in await _in(session, UserCollegeAssignment, UserCollegeAssignment.college_id, scope):
        reach[row.college_id].add(row.user_id)

    colleges = await _in(session, College, College.id, scope)
    by_cluster: dict[UUID, list[UUID]] = defaultdict(list)
    for college in colleges:
        if college.cluster_id is not None:
            by_cluster[college.cluster_id].append(college.id)
    if by_cluster:
        cluster_rows = await _in(
            session, UserClusterAssignment, UserClusterAssignment.cluster_id, list(by_cluster)
        )
        for row in cluster_rows:
            for cid in by_cluster.get(row.cluster_id, ()):
                reach[cid].add(row.user_id)

    grouped: _TierMap = {}
    for cid, user_ids in reach.items():
        per_tier: dict[EscalationTier, list[UUID]] = defaultdict(list)
        for user_id in user_ids:
            tier = tier_of.get(user_id)
            if tier is not None:
                per_tier[tier].append(user_id)
        for tier, ids in per_tier.items():
            # Stable order is part of the Protocol: an escalation that names its
            # recipients differently on every run is not deterministic.
            grouped[(tier, cid)] = tuple(sorted(ids))
    return _StaffDirectory(grouped)


# --- shaping the monitor's inputs ---------------------------------------------


def _assess_deployments(
    program: Program,
    deployments: Sequence[Deployment],
    marks: dict[UUID, list[TrainerAttendance]],
    start: dt.date,
    end: dt.date,
    observed_at: dt.datetime,
) -> list[tuple[Deployment, RiskAssessment, AttendanceSignal]]:
    """One assessment per deployment active in the window.

    The window is CLIPPED to the deployment's own dates. A trainer who started on
    the 20th has not failed to mark the 1st to the 19th, and a monitor that says
    otherwise fires on every new deployment in its first month — which is how an
    alert feed becomes something people close without reading.
    """
    out: list[tuple[Deployment, RiskAssessment, AttendanceSignal]] = []
    for deployment in deployments:
        window_start = max(start, deployment.start_date or start)
        window_end = min(end, deployment.end_date or end)
        if window_end < window_start:
            continue

        rows = [
            r for r in marks.get(deployment.id, ()) if window_start <= r.mark_date <= window_end
        ]
        signal = AttendanceSignal(
            period_start=window_start,
            period_end=window_end,
            # `expand_period` materialises UNMARKED for every day no row exists
            # for. A sparse list would make the one failure mode this whole
            # detector family exists to catch invisible (§5).
            days=tuple(
                expand_period(window_start, window_end, {r.mark_date: r.mark for r in rows})
            ),
            elapsed_through=min(window_end, observed_at.date()),
            last_marked_at=max((r.marked_at for r in rows), default=None),
        )
        assessment = assess_risk(
            MonitorContext(
                program_id=program.id,
                college_id=program.college_id,
                program_type=program.type,
                as_of=observed_at,
                attendance=signal,
                # usage / syllabus stay None — see the module docstring. The
                # detectors are silent on a missing signal by design; passing a
                # zero would be asserting a fact nobody measured (R1).
            )
        )
        out.append((deployment, assessment, signal))
    return out


def _deployment_out(
    deployment: Deployment,
    assessment: RiskAssessment,
    signal: AttendanceSignal,
    audience: Persona,
    *,
    trainer_name: str,
    batch_name: str,
) -> DeploymentRiskOut:
    """Render one assessment through `build_alert()` for this caller's persona.

    `build_alert` raises on an external audience. It cannot here — the handler
    ran `require_internal()` first — and the call is left un-guarded on purpose:
    if that ordering is ever broken, a 500 naming §8 is the correct outcome, not
    a quietly delivered alert.

    The window comes off the signal the monitor actually looked at, not off the
    request. They differ whenever a deployment starts or ends mid-period, and
    reporting the requested window against a clipped assessment is how "3 of 31
    days marked" gets read as a crisis.
    """
    alert = build_alert(assessment, (audience,))
    return DeploymentRiskOut(
        deployment_id=deployment.id,
        trainer_name=trainer_name,
        batch_name=batch_name,
        period_start=signal.period_start,
        period_end=signal.period_end,
        elapsed_through=signal.elapsed_through,
        score=assessment.score,
        band=assessment.band,
        headline=alert.headline,
        lines=alert.lines,
        anomalies=tuple(AnomalyOut.of(a) for a in assessment.anomalies),
    )


