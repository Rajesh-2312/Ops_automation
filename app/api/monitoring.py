#: The `SlaMetric` members this endpoint measures. The rest are omitted from
#: `SlaFacts.metrics` entirely, because `engine.evaluate_sla()` treats a missing
#: key as "not measured" and a present zero as a measurement — and an `LT` rule
#: against a defaulted zero fires on every subject nobody collected data for.
MEASURED_METRICS: Final[frozenset[SlaMetric]] = frozenset(
    {
        SlaMetric.TASK_HOURS_OVERDUE,
        SlaMetric.DOCUMENT_HOURS_UNSIGNED,
        SlaMetric.ATTENDANCE_UNMARKED_DAYS,
        SlaMetric.ATTENDANCE_HOURS_SINCE_MARK,
        SlaMetric.DELIVERY_RISK_SCORE,
    }
)


def _sla_metrics(
    assessed: Sequence[tuple[Deployment, RiskAssessment, AttendanceSignal]],
    tasks: Sequence[Task],
    documents: Sequence[ProgramDocument],
    observed_at: dt.datetime,
) -> dict[SlaMetric, Decimal]:
    """Measure, from the systems of record, what the rule table may refer to.

    Every value is a WORST CASE across the program: the most overdue task, the
    longest-unsigned document, the deployment with the most unmarked days, the
    stalest marking, the riskiest deployment. Averaging would let one healthy
    tracksheet hide a stopped one, and the SLA exists to notice the stopped one.

    A metric nobody could measure is left OUT of the mapping rather than set to
    zero. That is `engine.py`'s stated rule and it is load-bearing: an unmarked-
    day count of zero and an unmarked-day count nobody took are different facts.
    """
    metrics: dict[SlaMetric, Decimal] = {}

    overdue = [
        h
        for t in tasks
        if t.status is not TaskStatus.DONE and t.due_date is not None
        if (h := _hours_past(_end_of_day(t.due_date), observed_at)) is not None
    ]
    if overdue:
        metrics[SlaMetric.TASK_HOURS_OVERDUE] = max(overdue)

    unsigned = [
        h
        for d in documents
        if d.status != DocStatus.SIGNED and d.due_date is not None
        if (h := _hours_past(_end_of_day(d.due_date), observed_at)) is not None
    ]
    if unsigned:
        metrics[SlaMetric.DOCUMENT_HOURS_UNSIGNED] = max(unsigned)

    if assessed:
        unmarked = max(
            len([d for d in signal.elapsed_days() if d.mark is AttendanceMark.UNMARKED])
            for _, _, signal in assessed
        )
        metrics[SlaMetric.ATTENDANCE_UNMARKED_DAYS] = Decimal(unmarked)
        metrics[SlaMetric.DELIVERY_RISK_SCORE] = max(a.score for _, a, _ in assessed)

        # Hours SINCE a mark is unmeasurable when there has never been one. The
        # monitor already raises `attendance_marking_stale` for that case, so the
        # signal is not lost — it is just not expressible as an elapsed duration.
        stale = [
            h
            for _, _, signal in assessed
            if signal.last_marked_at is not None
            if (h := _hours_past(signal.last_marked_at, observed_at)) is not None
        ]
        if stale:
            metrics[SlaMetric.ATTENDANCE_HOURS_SINCE_MARK] = max(stale)

    return metrics


def _unmeasured(metrics: dict[SlaMetric, Decimal]) -> tuple[str, ...]:
    """Rule-table metrics this program carries no measurement for, in enum order."""
    return tuple(m.value for m in SlaMetric if m not in metrics)


# --- small conversions --------------------------------------------------------


def _as_of(as_of: dt.datetime | None) -> dt.datetime:
    """The observation instant, UTC (§11).

    The clock is read HERE and nowhere deeper: neither service calls
    `datetime.now()`, which is what makes a run reproducible from its inputs and
    lets a caller replay last Tuesday by passing `as_of`.
    """
    if as_of is None:
        return dt.datetime.now(dt.UTC)
    return as_of if as_of.tzinfo is not None else as_of.replace(tzinfo=dt.UTC)


def _period(
    period_start: dt.date | None, period_end: dt.date | None, observed_at: dt.datetime
) -> tuple[dt.date, dt.date]:
    """Resolve the observation window, defaulting to the calendar month of `as_of`.

    The month is the default because it is the period a payout cycle is cut on
    (§6), and the attendance gaps this feed exists to surface are the ones that
    block that cycle at month end.
    """
    today = observed_at.date()
    if period_start is None and period_end is None:
        last = calendar.monthrange(today.year, today.month)[1]
        return today.replace(day=1), today.replace(day=last)
    if period_start is None or period_end is None:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail="Give both period_start and period_end, or neither for the current month",
        )
    if period_end < period_start:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail=f"period_end {period_end} precedes period_start {period_start}",
        )
    if (period_end - period_start).days + 1 > MAX_PERIOD_DAYS:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail=(
                f"An observation window may span at most {MAX_PERIOD_DAYS} days; every day "
                "of it is materialised per deployment so that unmarked days are visible."
            ),
        )
    return period_start, period_end


def _end_of_day(on: dt.date) -> dt.datetime:
    """Midnight UTC ending `on` — the instant something due that day became late.

    Due dates are dates, and treating one as midnight at its START would report a
    task due today as a day overdue before the day has happened.
    """
    return dt.datetime.combine(on + dt.timedelta(days=1), dt.time.min, tzinfo=dt.UTC)


def _hours_past(deadline: dt.datetime, observed_at: dt.datetime) -> Decimal | None:
    """Hours from `deadline` to `observed_at`, or `None` if it has not passed."""
    seconds = (observed_at - deadline).total_seconds()
    if seconds <= 0:
        return None
    return (Decimal(seconds) / _SECONDS_PER_HOUR).quantize(_HOURS)
